import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));

const sharedFiles = [
  fileEntry('src/sanring-theme.css', 'registry/shared/theme.css'),
  contentEntry('src/app/components/ui/shared/utils.ts', stackBlitzUtils()),
  fileEntry(
    'src/app/components/ui/shared/component-styles.ts',
    'registry/shared/component-styles.ts',
  ),
];

const components = [
  {
    componentName: 'alert',
    files: [
      'alert/alert.component.ts',
      'alert/alert-description.directive.ts',
      'alert/alert.styles.ts',
      'alert/alert-title.directive.ts',
      'alert/alert.type.ts',
      'alert/index.ts',
    ],
  },
  {
    componentName: 'badge',
    files: [
      'badge/badge.directive.ts',
      'badge/badge.styles.ts',
      'badge/badge.type.ts',
      'badge/index.ts',
    ],
  },
  {
    componentName: 'button',
    files: [
      'button/button.directive.ts',
      'button/button.styles.ts',
      'button/button.types.ts',
      'button/index.ts',
    ],
  },
];

const entries = components.map((component) => ({
  componentName: component.componentName,
  files: Object.fromEntries([
    ...sharedFiles.map((file) => [file.target, file.content]),
    ...component.files.map((file) => [
      `src/app/components/ui/${file}`,
      read(`registry/components/${file}`),
    ]),
  ]),
}));

const output = `// Auto-generated by scripts/generate-stackblitz-registry.mjs.
// Do not edit by hand; update the component list in the script and regenerate.

import { StackBlitzRegistryEntry } from './registry-source';

export const generatedStackBlitzRegistryEntries: readonly StackBlitzRegistryEntry[] = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync(
  join(root, 'apps/docs/src/app/stackblitz/registry-source.generated.ts'),
  output,
  'utf-8',
);

function read(path) {
  return readFileSync(join(root, path), 'utf-8');
}

function fileEntry(target, source) {
  return { target, content: read(source) };
}

function contentEntry(target, content) {
  return { target, content };
}

function stackBlitzUtils() {
  return `type ClassValue = string | number | false | null | undefined;

export function cn(...inputs: ClassValue[]) {
  return inputs.filter(Boolean).join(' ');
}

export function uniqueId(prefix: string): string {
  return \`\${prefix}-\${Math.random().toString(36).slice(2, 10)}\`;
}
`;
}
